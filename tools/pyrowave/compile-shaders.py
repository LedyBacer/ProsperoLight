import hashlib, pathlib, subprocess, struct, tempfile
root=pathlib.Path(__file__).resolve().parents[2]
digest = hashlib.sha256(b''.join((root/'src/pyrowave/video'/('yuv.'+stage)).read_bytes() for stage in ['vert','frag'])).hexdigest()
lines=['// Generated by tools/pyrowave/compile-shaders.py; SPDX-License-Identifier: MIT', '// Shader sources SHA256: '+digest, '#pragma once','#include <cstdint>']
with tempfile.TemporaryDirectory() as temp:
    for stage in ['vert','frag']:
        target=pathlib.Path(temp)/('yuv.'+stage+'.spv')
        subprocess.run(['glslangValidator','-V','--target-env','vulkan1.3','-o',str(target),str(root/'src/pyrowave/video'/('yuv.'+stage))],check=True)
        data=target.read_bytes(); words=struct.unpack('<'+'I'*(len(data)//4),data)
        lines.append('inline constexpr uint32_t yuv_'+stage+'[] = {'+','.join(hex(w) for w in words)+'};')
(root/'src/pyrowave/video/yuv_spirv.hpp').write_text('\n'.join(lines)+'\n')
